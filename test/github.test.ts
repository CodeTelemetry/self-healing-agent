import { describe, expect, it } from "vitest";
import {
  extractClaudeSessionId,
  extractClaudeSessionIds,
  hasKnownIssueDisposition,
  normalizeSessionId,
  pullRequestEventOrder,
  timingSafeSignatureHeader,
} from "../src/domain/github.js";

describe("GitHub PR correlation", () => {
  it("extracts and normalizes Claude session links", () => {
    expect(extractClaudeSessionId("Generated by https://claude.ai/code/session_abc-123")).toBe("session_abc-123");
    expect(extractClaudeSessionId("https://claude.ai/code/cse_abc_123?from=web")).toBe("session_abc_123");
    expect(normalizeSessionId("cse_test")).toBe("session_test");
  });

  it("finds every linked session so reused PRs can join the active generation", () => {
    expect(extractClaudeSessionIds(
      "Prior https://claude.ai/code/session_old and current https://claude.ai/code/cse_current",
    )).toEqual(["session_old", "session_current"]);
    expect(extractClaudeSessionIds(undefined)).toEqual([]);
  });

  it("recognizes explicit known-issue disposition and deterministically orders same-second events", () => {
    expect(hasKnownIssueDisposition("<!-- self-healing-disposition: known-issue -->")).toBe(true);
    expect(hasKnownIssueDisposition("closed as duplicate")).toBe(false);
    const timestamp = "2026-08-27T12:00:00Z";
    expect(pullRequestEventOrder(timestamp, "closed", "closed", false).localeCompare(
      pullRequestEventOrder(timestamp, "reopened", "open", false),
    )).toBeLessThan(0);
    expect(pullRequestEventOrder(timestamp, "reopened", "open", false).localeCompare(
      pullRequestEventOrder(timestamp, "closed", "closed", true),
    )).toBeLessThan(0);
  });

  it("rejects missing or malformed signatures", () => {
    expect(timingSafeSignatureHeader(undefined)).toBeUndefined();
    expect(timingSafeSignatureHeader("sha1=abc")).toBeUndefined();
    expect(timingSafeSignatureHeader(`sha256=${"a".repeat(64)}`)).toBe("a".repeat(64));
  });
});
